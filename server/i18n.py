def system_lang():
    """Idioma de Windows (o del locale) si está soportado; si no, inglés."""
    code = None
    if sys.platform == "win32":
        try:
            import ctypes
            code = locale.windows_locale.get(ctypes.windll.kernel32.GetUserDefaultUILanguage())
        except Exception:
            code = None
    if not code:
        try:
            code = locale.getlocale()[0]
        except Exception:
            code = None
    code = (code or "en")[:2].lower()
    return code if code in STRINGS else "en"


class Translator:
    def __init__(self, lang=None):
        self.lang = lang if lang in STRINGS else system_lang()

    def __call__(self, key, **kw):
        text = STRINGS[self.lang].get(key) or STRINGS["en"][key]
        return text.format(**kw) if kw else text
